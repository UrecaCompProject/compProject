import { PromptTemplate } from 'npm:@langchain/core/prompts';

/**
 * 관련 기능
 * - F-08 사용자 조건 분석
 *
 * 목적
 * - 사용자의 자연어 메시지를 분석하여 상담 의도(Intent)를 분류
 * - 분류 결과에 따라 recommend / usageAnalysis / compare 등의 Prompt 선택
 *
 * 현재 Intent
 * - recommend: 요금제 추천 요청
 * - usage_analysis: 현재 사용량 또는 사용 패턴 분석 요청
 * - compare: 요금제 비교 요청
 * - general: 위 항목에 해당하지 않는 일반 상담
 *
 * 추후 기능 확장에 따라 Intent 종류 추가 가능
 */
export const intentPrompt = PromptTemplate.fromTemplate(`
[ROLE]

당신은 AI 통신 상담 서비스에서
사용자의 메시지가 어떤 상담 기능을 요청하는지 분류하는 역할을 담당합니다.


[사용자 메시지]

{userMessage}


[이전 상담 맥락]

{conversationContext}


[INTENT]

다음 Intent 중 가장 적합한 하나를 선택하세요.


1. recommend

사용자가 자신의 조건에 맞는 요금제를 추천받고자 하는 경우입니다.

예시:
- "나한테 맞는 요금제 추천해줘."
- "데이터 많이 쓰는데 어떤 요금제가 좋아?"
- "6만원 이하로 괜찮은 요금제 있어?"
- "OTT 혜택 있는 요금제 추천해줘."


2. usage_analysis

사용자가 자신의 현재 사용량이나
현재 요금제가 사용 패턴에 적합한지 분석받고자 하는 경우입니다.

예시:
- "내 데이터 사용량 많은 편이야?"
- "지금 요금제가 나한테 적당해?"
- "최근 사용량 분석해줘."
- "요즘 데이터를 너무 많이 쓰는 것 같아."


3. compare

사용자가 두 개 이상의 요금제 차이,
장단점 또는 어떤 요금제가 더 적합한지 묻는 경우입니다.

예시:
- "A랑 B 중에 뭐가 좋아?"
- "아까 추천한 1순위랑 2순위 비교해줘."
- "이 두 요금제 차이가 뭐야?"
- "둘 중 나한테 더 맞는 건 뭐야?"


4. general

추천, 사용량 분석, 요금제 비교에 해당하지 않는
일반적인 통신 상담 질문입니다.

예시:
- "테더링이 뭐야?"
- "공유 데이터가 무슨 뜻이야?"
- "요금제 변경은 어떻게 해?"


[RULES]

1. 사용자 메시지의 핵심 목적을 기준으로 분류하세요.

2. 단순히 특정 단어가 포함되었다는 이유만으로 분류하지 말고
   전체 문장의 의도를 확인하세요.

3. 이전 상담에서 추천 요금제가 이미 존재하고
   사용자가 "둘 중 뭐가 좋아?"처럼 질문한 경우 compare로 분류하세요.

4. 사용자가 현재 사용 상태를 묻고
   아직 직접적인 추천을 요청하지 않았다면 usage_analysis를 우선 고려하세요.

5. 사용자가 현재 문제를 설명하면서
   새로운 요금제를 찾아달라는 의미를 함께 표현했다면 recommend로 분류할 수 있습니다.

6. 여러 Intent가 동시에 포함된 경우
   사용자가 최종적으로 원하는 행동을 기준으로 하나를 선택하세요.

7. 반드시 아래 Intent 중 하나만 반환하세요.
   - recommend
   - usage_analysis
   - compare
   - general


[OUTPUT]

반드시 아래 형식의 유효한 JSON만 출력하세요.

{{
  "intent": "recommend"
}}

JSON 이외의 추가 설명 문장은 포함하지 마세요.
`);